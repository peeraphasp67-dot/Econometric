def get_word_bank(lang) -> dict:
    return WORD_BANK.get(lang) or WORD_BANK[DEFAULT_LANG]


def t(key: str, lang: str = DEFAULT_LANG) -> str:
    """Look up `key` in `lang`, falling back to English, then to the raw key.

    Defensive against every invalid-input case: `lang` missing/None/empty/
    unknown code, or `key` absent from that language's dictionary (or even
    from English) all resolve safely instead of raising.
    """
    if not key:
        return key
    lang_dict = TRANSLATIONS.get(lang) if lang else None
    if lang_dict:
        val = lang_dict.get(key)
        if val is not None:
            return val
    return TRANSLATIONS[DEFAULT_LANG].get(key, key)


